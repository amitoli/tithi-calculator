import { createEvents, type EventAttributes } from "ics";
import { localDateParts } from "../timezone";
import type { CalculationResult, Milestone } from "../panchang/types";

function eventFromMilestone(item: Milestone, timeZone: string, familyLabel: string): EventAttributes {
  const p = localDateParts(item.date, timeZone);
  return {
    title: `${item.title}${familyLabel}`,
    description: `${item.subtitle}\n${item.notes}\n\nTithi: ${item.tithiName}${item.nepaliDate ? `\nNepali date: ${item.nepaliDate}` : ""}\nGenerated by Tithi & Barshik Companion.`,
    start: [p.year, p.month, p.day, 13, 15],
    startInputType: "local",
    duration: { hours: 2, minutes: 15 },
    status: "CONFIRMED",
    busyStatus: "BUSY",
    calName: "Barshik Milestones",
    productId: "tithi-barshik-companion",
    categories: ["shraddha", "barshik"],
  };
}

export function buildMilestoneIcs(result: CalculationResult): string {
  const familyLabel = "";
  const firstYear = result.timeline.filter((item) => item.kind !== "civil");
  const laterAnnual = result.annualShraddha.filter((item) => item.kind === "annual");
  const events = [...firstYear, ...laterAnnual].map((item) =>
    eventFromMilestone(item, result.input.location.timeZone, familyLabel),
  );

  const { error, value } = createEvents(events);
  if (error || !value) {
    throw new Error(error?.message ?? "Could not build calendar file");
  }
  return value;
}

export function downloadIcs(result: CalculationResult) {
  const ics = buildMilestoneIcs(result);
  const blob = new Blob([ics], { type: "text/calendar;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = "barshik-milestones.ics";
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}
